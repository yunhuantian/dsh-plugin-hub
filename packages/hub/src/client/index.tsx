export const inject = ['slots', 'locale', 'remote'];

/**
 * 商店面板：注册进官方「插件」页的一个条目（`plugins.item`）。
 *
 * ⚠️ **官方会拿同一个组件渲染两次**，靠 `view` 区分 —— 这是踩过一次才看清的契约：
 *
 *   renderSlot("plugins.item", { view: "summary" }, { only: id })   // 列表里那张卡片
 *   renderSlot("plugins.item", { view: "page", form }, { only: id }) // 点进去的详情页
 *
 * 之前这里无视 `view` 直接渲染整个商店，于是**卡片里被塞进了整个商店**：
 * 列表里一排官方条目（终端 / Agent 循环 / 网页搜索…）各占一行，紧接着就是我们
 * 整块商店展开，非常突兀。正确做法是 summary 只给一行摘要 ——
 * 标题、图标、点击热区和「返回列表」都由官方那套渲染，我们一格自定义 chrome 都不用加。
 */
function StorePluginsTab({ view, api, t }: { view?: string; api: RemoteApi; t: (k: string) => string }): ReactNode {
  if (view === 'summary') return <>{t('entry.summary')}</>;
  return <StoreApp api={api} t={t} />;
}

/**
 * Mount the Remote contribution and register the native integration points.
 */
export async function apply(ctx: any): Promise<() => Promise<void>> {
  const disposeRemote = await ctx.remote.$mount(TYPERT_REMOTE);
  const disposeLocale = ctx.locale.register(NS, { zh, en });
  // 内置扩展的字典也在这里注册：hub 一个包只有一份 client bundle。
  const disposeUsageLocale = ctx.locale.register(USAGE_NS, usageDictionaries);

  /** 内置扩展注册的 UI feature（与 hub 核心一起收放）。 */
  const extensionFeatures: Array<{ dispose: () => Promise<void> }> = [];
  let disposed = false;

  const feature = ctx.inject(['remote.pluginStore'], (scope: any) => {
    const api: RemoteApi = makeApi(scope.remote);
    const t = ctx.locale.bind(NS);

    // 唯一对外的界面接入点：官方「插件」页（侧栏「插件」，intro 写着"安装、启用和
    // 配置插件"）里的一个条目。
    //
    // 该页由 dsh-client-ui-plugin-manager 拥有（注册 `main` 槽、key = "plugins"），
    // 并声明了子槽 `plugins.item`（list）。官方自己的插件配置卡就是这么挂的
    // （如 dsh-client-ui-settings-shell），点条目会进入一个独立视图
    // （页面内部 `view.kind === 'item'`）—— 正好适合商店这种大界面。
    scope.slots.inject('plugins.item', () => scope.slots.register({
      name: 'plugins.item',
      id: 'plugin-store',
      order: 90,
      label: () => t('entry.label'),
      locale: NS,
      inject: () => ({ api, t }),
    }, StorePluginsTab));

    // 内置扩展的 UI（0.2：hub 一个包、多个可开关的内部插件）。
    //
    //    开关的唯一来源是 host 的 `extensions` Remote（它读的是扩展自己也在读的
    //    那份 `extensions.json`）。于是"host 让位"与"UI 不出现"天然一致 ——
    //    不会再出现 0.1.x 那种重复注册（两个「用量」tab）或注册了却没有服务的半死状态。
    //
    //    注意：视图必须挂在 hub 的 client 里（一个包只能有一份 client 产物，
    //    见 harness 的 dsh.client 契约），所以扩展是"内部模块"而不是独立包。
    void scope.remote.pluginStore.extensions().then((snapshot: { rows?: Array<{ id: string; enabled: boolean }> }) => {
      if (disposed) return;
      const enabled = new Set((snapshot?.rows ?? []).filter((row) => row.enabled).map((row) => row.id));
      if (enabled.has('usage')) extensionFeatures.push(mountUsageView(ctx));
    }).catch(() => { /* 读不到开关时只挂核心 UI，不影响商店本身 */ });

    return () => {};
  });

  return async () => {
    disposed = true;
    for (const extension of extensionFeatures.splice(0)) {
      try { await extension.dispose(); } catch { /* 已随包卸载 */ }
    }
    await feature.dispose();
    disposeLocale();
    disposeUsageLocale();
    await disposeRemote();
  };
}

export default { apply, inject };
